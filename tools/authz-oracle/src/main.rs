//! The Cedar decision oracle (ADR 0013 D10, story 72a): generate policy
//! sets in the subset graph-authz accepts, print them with graph-authz's
//! printer, and check that
//!
//! 1. `cedar-policy` parses every printed set (every accepted file is valid
//!    Cedar), including the comment forms the subset accepts, and
//! 2. both engines decide every (principal, action, resource) request over
//!    the checked-in `entities.json` identically (`schema.cedarschema`
//!    validates the requests).
//!
//! A disagreement is written to `--fixtures <dir>` (default
//! `testdata/authz/`) as `oracle-<seed>-<case>.cedar` plus `.requests`, with
//! Cedar's decision as the expected one, so `cargo test -p graph-authz`
//! replays it without Cedar; the run then exits 1.
//!
//! `cargo run --release --manifest-path tools/authz-oracle/Cargo.toml -- [--cases N] [--seed S] [--fixtures DIR]`
use cedar_policy::{
    Authorizer, Context, Decision, Entities, EntityUid, PolicySet, Request, Schema,
};
use graph_authz::{Action, ActionScope, Effect, Entity, Policy, Resource, Role, Scope, Ty};
use std::path::PathBuf;
use std::str::FromStr;

/// A small deterministic generator (xorshift64*), so a seed reproduces a run.
struct Rng(u64);

impl Rng {
    fn next(&mut self) -> u64 {
        let mut x = self.0;
        x ^= x >> 12;
        x ^= x << 25;
        x ^= x >> 27;
        self.0 = x;
        x.wrapping_mul(0x2545_f491_4f6c_dd1d)
    }
    fn below(&mut self, n: usize) -> usize {
        (self.next() % n as u64) as usize
    }
    fn pick<'a, T>(&mut self, v: &'a [T]) -> &'a T {
        &v[self.below(v.len())]
    }
}

const TOKENS: [&str; 5] = ["t0", "t1", "t2", "t3", "nobody"];
const GROUPS: [&str; 4] = ["g0", "g1", "g2", "empty"];
const ORGS: [&str; 4] = ["o0", "o1", "o0/x", "zz"];
const REPOS: [&str; 6] = ["o0/r0", "o0/r1", "o1/r0", "o1/a/b", "o0/x/r", "zz/q"];

fn principal_scope(r: &mut Rng) -> Scope {
    let e = match r.below(3) {
        0 => Entity { ty: Ty::Token, id: r.pick(&TOKENS).to_string() },
        1 => Entity { ty: Ty::Group, id: r.pick(&GROUPS).to_string() },
        _ => Entity { ty: Ty::Role, id: r.pick(&["read", "write"]).to_string() },
    };
    match r.below(4) {
        0 => Scope::Any,
        1 => Scope::Eq(e),
        _ => Scope::In(e),
    }
}

fn resource_entity(r: &mut Rng) -> Entity {
    match r.below(5) {
        0 | 1 => Entity { ty: Ty::Org, id: r.pick(&ORGS).to_string() },
        2 | 3 => Entity { ty: Ty::Repo, id: r.pick(&REPOS).to_string() },
        _ => Entity { ty: Ty::Cluster, id: "this".into() },
    }
}

fn policy(r: &mut Rng, n: usize) -> Policy {
    let action = match r.below(4) {
        0 => ActionScope::Any,
        1 => ActionScope::Eq(*r.pick(&Action::ALL)),
        _ => ActionScope::In((0..r.below(4)).map(|_| *r.pick(&Action::ALL)).collect()),
    };
    let resource = match r.below(3) {
        0 => Scope::Any,
        1 => Scope::Eq(resource_entity(r)),
        _ => Scope::In(resource_entity(r)),
    };
    let id = format!("p{n}");
    Policy {
        id: id.clone(),
        annotations: vec![("id".into(), Some(id))],
        effect: if r.below(3) == 0 { Effect::Forbid } else { Effect::Permit },
        principal: principal_scope(r),
        action,
        resource,
        line: 0,
    }
}

/// The printed set, with line comments sprinkled in. Block comments are
/// probed once in `main` instead: cedar-policy refuses them while ADR 0013
/// D2 lists them as accepted (an open question for the owner).
fn print_set(r: &mut Rng, ps: &[Policy]) -> String {
    let mut s = String::from("// generated by tools/authz-oracle\n");
    for p in ps {
        if r.below(3) == 0 {
            s.push_str("// a line comment\n");
        }
        s.push_str(&p.to_string());
        s.push('\n');
    }
    s
}

struct Who {
    token: &'static str,
    groups: Vec<String>,
    role: Role,
}

/// The principals of `entities.json` as graph-authz sees them.
fn principals() -> Vec<Who> {
    let g = |v: &[&str]| v.iter().map(|s| s.to_string()).collect();
    vec![
        Who { token: "t0", groups: g(&["g0"]), role: Role::Write },
        Who { token: "t1", groups: g(&["g0", "g1"]), role: Role::Read },
        Who { token: "t2", groups: g(&[]), role: Role::Write },
        Who { token: "t3", groups: g(&["g2"]), role: Role::Write },
    ]
}

fn resources() -> Vec<Entity> {
    let mut v: Vec<Entity> = ORGS[..3]
        .iter()
        .map(|o| Entity { ty: Ty::Org, id: o.to_string() })
        .collect();
    v.extend(
        ["o0/r0", "o0/r1", "o1/r0", "o1/a/b"]
            .iter()
            .map(|r| Entity { ty: Ty::Repo, id: r.to_string() }),
    );
    v.push(Entity { ty: Ty::Cluster, id: "this".into() });
    v
}

fn main() {
    let mut cases = 2_000usize;
    let mut seed = 0x5eed_u64;
    let mut fixtures = PathBuf::from("testdata/authz");
    let mut args = std::env::args().skip(1);
    while let Some(a) = args.next() {
        let v = args.next().unwrap_or_else(|| panic!("{a} needs a value"));
        match a.as_str() {
            "--cases" => cases = v.parse().expect("--cases N"),
            "--seed" => seed = v.parse().expect("--seed S"),
            "--fixtures" => fixtures = PathBuf::from(v),
            _ => panic!("unknown argument {a}"),
        }
    }
    let here = PathBuf::from(env!("CARGO_MANIFEST_DIR"));
    let (schema, _) =
        Schema::from_cedarschema_str(&std::fs::read_to_string(here.join("schema.cedarschema")).unwrap())
            .expect("the schema parses");
    let entities = Entities::from_json_str(
        &std::fs::read_to_string(here.join("entities.json")).unwrap(),
        Some(&schema),
    )
    .expect("the entities validate");
    // ADR 0013 D2 accepts `/* */` comments "(Cedar has both)"; report what
    // this cedar-policy does with them without failing the decision check.
    let block = "/* c */ permit(principal, action, resource);";
    if PolicySet::from_str(block).is_err() {
        println!(
            "NOTE: cedar-policy refuses `/* */` comments, which graph-authz accepts per ADR 0013 \
             D2; a file using them is not valid Cedar (open ADR question)"
        );
    }
    let auth = Authorizer::new();
    let who = principals();
    let res = resources();
    let mut rng = Rng(seed.max(1));
    let (mut decisions, mut disagreements) = (0usize, 0usize);
    for case in 0..cases {
        let ps: Vec<Policy> = (0..1 + rng.below(8)).map(|n| policy(&mut rng, n)).collect();
        let text = print_set(&mut rng, &ps);
        let ours = graph_authz::PolicySet::new(
            graph_authz::parse(text.as_bytes()).unwrap_or_else(|e| panic!("we refuse our own print: {e}\n{text}")),
        );
        let cedar = match PolicySet::from_str(&text) {
            Ok(p) => p,
            Err(e) => {
                eprintln!("case {case}: cedar-policy refuses a set graph-authz accepts: {e}\n{text}");
                std::process::exit(1);
            }
        };
        let mut bad = Vec::new();
        for w in &who {
            for a in Action::ALL {
                for e in &res {
                    let uid = |ty: &str, id: &str| {
                        EntityUid::from_str(&format!("{ty}::\"{}\"", graph_authz::escape(id))).unwrap()
                    };
                    let req = Request::new(
                        uid("Token", w.token),
                        uid("Action", a.name()),
                        uid(e.ty.name(), &e.id),
                        Context::empty(),
                        Some(&schema),
                    )
                    .expect("the request validates");
                    let c = auth.is_authorized(&req, &cedar, &entities).decision() == Decision::Allow;
                    // The role ceiling is the server's, outside Cedar (D4).
                    let want = c && w.role.ceiling() & a.bit() != 0;
                    let r: Resource<'_> = e.as_resource().unwrap();
                    let got = ours
                        .decide(&graph_authz::Principal { token: w.token, groups: &w.groups, role: w.role }, a, &r)
                        .allowed;
                    decisions += 1;
                    if got != want {
                        bad.push(format!(
                            "{}\t{}\t{}\t{}\t{}\t{}",
                            w.token,
                            w.groups.join(","),
                            match w.role { Role::Read => "read", Role::Write => "write" },
                            a.name(),
                            r,
                            if want { "allow" } else { "deny" }
                        ));
                    }
                }
            }
        }
        if !bad.is_empty() {
            disagreements += bad.len();
            let base = fixtures.join(format!("oracle-{seed}-{case}"));
            std::fs::write(base.with_extension("cedar"), &text).unwrap();
            std::fs::write(
                base.with_extension("requests"),
                format!("# token\tgroups\trole\taction\tresource\tdecision (cedar-policy's)\n{}\n", bad.join("\n")),
            )
            .unwrap();
            eprintln!("case {case}: {} disagreements, saved to {}", bad.len(), base.display());
        }
    }
    println!("{cases} policy sets, {decisions} decisions, {disagreements} disagreements");
    if disagreements > 0 {
        std::process::exit(1);
    }
}
